#!/usr/bin/env bash
# Regenerates constraints.txt: the exact versions of everything pyproject.toml's dependency
# groups install, resolved in a fresh throwaway virtual environment.
# Run it deliberately when upgrading dependencies, then rerun ./init.sh and the notebooks.
set -euo pipefail
cd "$(dirname "$0")"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

python3 -m venv "$work/venv"
"$work/venv/bin/python" -m pip install --quiet --upgrade 'pip>=25.1'  # dependency groups need pip >= 25.1
"$work/venv/bin/python" -m pip install --quiet --group notebooks

{
    echo "# Generated by update-constraints.sh on $(date -u +%Y-%m-%d)" \
         "with Python $("$work/venv/bin/python" -c 'import platform; print(platform.python_version(), platform.machine())')."
    echo "# Exact versions for pyproject.toml's dependency groups, used by init.sh. Do not edit by hand."
    # --all keeps setuptools, which the build group needs; pip itself is managed by init.sh
    "$work/venv/bin/python" -m pip freeze --all --exclude pip
} > constraints.txt

echo "constraints.txt: $(grep -vc '^#' constraints.txt) pinned packages"
